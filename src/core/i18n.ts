let currentLang: Lang = 'kab';

export function setLang(lang: Lang) {
  currentLang = lang;
  try { localStorage.setItem('hakimos.lang', lang); } catch { /* quota */ }
}

export function getLang(): Lang {
  try {
    const saved = localStorage.getItem('hakimos.lang') as Lang | null;
    if (saved && translations[saved]) { currentLang = saved; return saved; }
  } catch { /* ignore */ }
  return currentLang;
}

export function t(key: string): string {
  return translations[currentLang]?.[key] ?? translations.en[key] ?? key;
}

export function dir(): 'rtl' | 'ltr' {
  return currentLang === 'ar' ? 'rtl' : 'ltr';
}
